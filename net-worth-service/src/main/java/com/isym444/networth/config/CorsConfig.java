package com.isym444.networth.config;

import org.springframework.beans.factory.annotation.Value;
import org.springframework.boot.web.servlet.FilterRegistrationBean;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.core.Ordered;
import org.springframework.web.cors.CorsConfiguration;
import org.springframework.web.cors.UrlBasedCorsConfigurationSource;
import org.springframework.web.filter.CorsFilter;

import java.util.List;

/**
 * Allows the Angular frontend's origin to call /api/**. Registered as a
 * CorsFilter (not WebMvcConfigurer.addCorsMappings) at highest precedence
 * so CORS headers apply even to responses generated by earlier filters
 * (e.g. AccessKeyFilter's 401) or Spring's /error dispatch — a plain
 * WebMvcConfigurer registration only applies inside the DispatcherServlet,
 * downstream of the filter chain.
 */
@Configuration
public class CorsConfig {

    @Value("${networth.cors.frontend-origin}")
    private String frontendOrigin;

    @Bean
    public FilterRegistrationBean<CorsFilter> corsFilter() {
        String[] origins = frontendOrigin.split(",");
        for (int i = 0; i < origins.length; i++) {
            origins[i] = origins[i].trim();
        }

        CorsConfiguration config = new CorsConfiguration();
        config.setAllowedOrigins(List.of(origins));
        config.setAllowedMethods(List.of("GET", "POST", "OPTIONS"));
        config.setAllowedHeaders(List.of("X-Api-Key", "Content-Type"));
        config.setMaxAge(3600L);

        UrlBasedCorsConfigurationSource source = new UrlBasedCorsConfigurationSource();
        source.registerCorsConfiguration("/api/**", config);

        FilterRegistrationBean<CorsFilter> bean = new FilterRegistrationBean<>(new CorsFilter(source));
        bean.setOrder(Ordered.HIGHEST_PRECEDENCE);
        return bean;
    }
}
